export function translate(language: UserPreferredLanguage | undefined, key: TranslationKey): string {
  const selected = hasConfiguredLanguage(language) ? language : "fr";
  return translations[selected][key] || translations.en[key] || translations.fr[key] || key;
}

export function createTranslator(language: UserPreferredLanguage | undefined): (key: TranslationKey) => string {
  return (key) => translate(language, key);
}
