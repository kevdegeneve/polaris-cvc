export function getLanguageLabel(language: UserPreferredLanguage): string {
  return languageOptions.find((item) => item.value === language)?.label || language;
}

export function hasConfiguredLanguage(value?: string): value is UserPreferredLanguage {
  return languageOptions.some((item) => item.value === value);
}

